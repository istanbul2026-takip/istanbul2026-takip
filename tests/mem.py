done = lambda p: json.loads(p.evaluate("localStorage.getItem('tarz-done')") or '[]')

print('M1 two tabs never overwrite each other')
a = s.page('/tarz/', NOW); adv(a, 4); b = s.page('/tarz/', NOW); adv(b, 4)
a.locator('.crow .tick').nth(0).click(); a.wait_for_timeout(80)
b.wait_for_timeout(150)
ok(b.locator('.crow .tick.on').count()==1, 'mark made in tab A appears in tab B')
b.locator('.crow .tick').nth(2).click(); b.wait_for_timeout(80)
a.locator('.crow .tick').nth(4).click(); a.wait_for_timeout(120)
ok(len(done(a))==3, 'three marks from two tabs are all kept', done(a))
# tab B frozen (no storage events): it must still not lose A's marks when it saves
b.evaluate("() => { window.stop && 0; }")
a.evaluate("() => { const add = n => { myNotes.push(n); }; }")
a.locator('#cNote').click(); a.fill('#nTime','10:00'); a.fill('#nText','A sekmesi'); a.locator('#nSave').click(); a.wait_for_timeout(100)
b.locator('#cNote').click(); b.fill('#nTime','11:00'); b.fill('#nText','B sekmesi'); b.locator('#nSave').click(); b.wait_for_timeout(100)
ok(len(json.loads(a.evaluate("localStorage.getItem('tarz-mynotes')")))==2, 'notes from both tabs kept')
ok('B sekmesi' in a.inner_text('#clubBox') and 'A sekmesi' in b.inner_text('#clubBox'), 'both tabs show both notes')
a.close(); b.close()

